def main() -> None:
    noise = json.loads((ROOT / "data" / "log_noise.json").read_text(encoding="utf-8"))
    rng = random.Random(SEED)
    out = {}
    for tid, t in TRAVELERS.items():  # 여행자 순서대로 같은 난수열을 쓰므로 재현된다
        mem = list(t["travel"]) + [f"{rng.choice(NOISE_DAYS)} {e}" for e in rng.sample(noise, N_NOISE)]
        mem.sort(key=lambda m: m[:5])  # 날짜순 (같은 날은 손으로 쓴 기록이 먼저)
        out[tid] = {"profile": t["profile"], "memories": mem, "n_travel": len(t["travel"])}
    meta = {"seed": SEED, "noise_per_traveler": N_NOISE, "source": "hand-written travel entries + log_noise.json",
            "note": "발화·정답보다 먼저 고정. 의도를 가르는 정보는 memories 에만 있다"}
    path = ROOT / "data" / "travel" / "travelers.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps({"meta": meta, "travelers": out}, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("ok", {k: len(v["memories"]) for k, v in out.items()})


if __name__ == "__main__":
    main()
